    def kill_player(self):
        p = self.player
        if p.dead:
            return
        p.dead = 70
        p.vy = -9
        self.snd.play("die")
        self.shake = 10

    def after_death(self):
        if self.hearts <= 0:
            self.state = "over"
            self.build_ui()
            return
        lvl = self.lvl
        x, y = self.respawn
        p = Player(x, y)
        p.inv = 80
        p.face = 1
        self.player = p
        for key in lvl.crumbles:
            lvl.crumbles[key] = [0, 0]
        if lvl.boss and not lvl.boss.dead:
            lvl.boss.reset()
            lvl.gate_closed = False
            lvl.enemies = [e for e in lvl.enemies if e.kind != "d"]
        self.cam = self.cam_target()

    def complete(self):
        lvl = self.lvl
        key = str(lvl.idx)
        rec = self.save["lv"].get(key, {})
        stars = set(rec.get("stars", [])) | self.got_stars
        best_t = rec.get("time")
        self.new_record = best_t is None or self.time < best_t
        rec = {"stars": sorted(stars), "coins": max(rec.get("coins", 0), self.got_coins),
               "time": round(self.time if self.new_record else best_t, 1)}
        self.save["lv"][key] = rec
        self.save["unlocked"] = max(self.save["unlocked"], min(len(LEVELS), lvl.idx + 2))
        write_save(self.save)
        self.state = "win"
        self.build_ui()

