class Pen:
    """Mantiqiy oʻlchamdagi kanvas: koordinatalar katakdagi birliklarda, ichida SS marta katta."""

    def __init__(self, wl, hl, k):
        self.wl, self.hl, self.k = wl, hl, k
        self.u = k * SS
        self.s = pygame.Surface((max(1, int(wl * self.u)), max(1, int(hl * self.u))), pygame.SRCALPHA)

    def P(self, x, y):
        return (x * self.u, y * self.u)

    def R(self, x, y, w, h):
        u = self.u
        return pygame.Rect(int(x * u), int(y * u), max(1, int(w * u)), max(1, int(h * u)))

    def oval(self, col, cx, cy, rx, ry, o=1.4, oc=OUT):
        if o:
            pygame.draw.ellipse(self.s, oc, self.R(cx - rx - o, cy - ry - o, 2 * (rx + o), 2 * (ry + o)))
        pygame.draw.ellipse(self.s, col, self.R(cx - rx, cy - ry, 2 * rx, 2 * ry))

    def circle(self, col, cx, cy, r, o=0, oc=OUT):
        if o:
            pygame.draw.circle(self.s, oc, self.P(cx, cy), (r + o) * self.u)
        pygame.draw.circle(self.s, col, self.P(cx, cy), r * self.u)

    def poly(self, col, pts, o=1.3, oc=OUT):
        pp = [self.P(*p) for p in pts]
        pygame.draw.polygon(self.s, col, pp)
        if o:
            pygame.draw.polygon(self.s, oc, pp, max(1, int(o * self.u)))

    def line(self, col, a, b, w=1.0):
        pygame.draw.line(self.s, col, self.P(*a), self.P(*b), max(1, int(w * self.u)))

    def rect(self, col, x, y, w, h, r=0, o=0, oc=OUT):
        if o:
            pygame.draw.rect(self.s, oc, self.R(x - o, y - o, w + 2 * o, h + 2 * o), border_radius=int((r + o) * self.u) if r else 0)
        pygame.draw.rect(self.s, col, self.R(x, y, w, h), border_radius=int(r * self.u) if r else 0)

    def tube(self, pts, r0, r1, col, o=1.3, cols=None):
        n = len(pts)
        rs = [r0 + (r1 - r0) * i / max(1, n - 1) for i in range(n)]
        if o:
            for (x, y), r in zip(pts, rs):
                pygame.draw.circle(self.s, OUT, self.P(x, y), (r + o) * self.u)
        for i, ((x, y), r) in enumerate(zip(pts, rs)):
            pygame.draw.circle(self.s, cols[i] if cols else col, self.P(x, y), r * self.u)

    def done(self):
        size = (max(1, round(self.wl * self.k)), max(1, round(self.hl * self.k)))
        return pygame.transform.smoothscale(self.s, size).convert_alpha()


def bezier(p0, p1, p2, n):
    out = []
    for i in range(n):
        t = i / (n - 1)
        a, b, c = (1 - t) ** 2, 2 * (1 - t) * t, t * t
        out.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))
    return out


def seg_pts(a, b, n=6):
    return [(a[0] + (b[0] - a[0]) * i / (n - 1), a[1] + (b[1] - a[1]) * i / (n - 1)) for i in range(n)]


