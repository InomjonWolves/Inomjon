    def puff(self, x, y, n):
        for _ in range(n):
            self.parts.append([x + random.uniform(-6, 6), y - random.uniform(0, 4), random.uniform(-1.4, 1.4), random.uniform(-1.6, -0.2), 22, 22, (236, 236, 244), random.uniform(3, 5.5), 0.04])

    def burst(self, x, y, col, n):
        for _ in range(n):
            a = random.uniform(0, 6.28)
            v = random.uniform(1.5, 5)
            self.parts.append([x, y, math.cos(a) * v, math.sin(a) * v - 1.5, 34, 34, col, random.uniform(2.5, 4.5), 0.18])

    def confetti(self, n, screen=False):
        cols = [(255, 90, 100), (255, 210, 60), (90, 200, 120), (90, 150, 255), (220, 120, 240)]
        for _ in range(n):
            x = (0 if screen else self.cam) + random.uniform(0, self.W / self.k if screen else self.vw_l)
            self.parts.append([x, random.uniform(-40, 0), random.uniform(-1.5, 1.5), random.uniform(1, 3.5), 140, 140, random.choice(cols), random.uniform(3, 5), 0.03])

