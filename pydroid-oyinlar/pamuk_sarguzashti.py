class Platform:
    def __init__(self, tx, ty, axis):
        self.bx, self.by = tx * TILE, ty * TILE
        self.x, self.y = self.bx, self.by
        self.w, self.h = 96, 16
        self.axis = axis
        self.dx = self.dy = 0.0
        self.t = (tx * 37) % 240
        self.period = 260 if axis == "x" else 230

    def update(self):
        self.t += 1
        s = math.sin(self.t * 2 * math.pi / self.period) * 96
        ox, oy = self.x, self.y
        if self.axis == "x":
            self.x = self.bx + s
        else:
            self.y = self.by + s
        self.dx, self.dy = self.x - ox, self.y - oy


def move_body(b, lvl, dx, dy, plats=None, oneway=True):
    """Kataklar bilan toʻqnashuvli harakat: (devor, yerga tushdi, shiftga urildi, platforma)"""
    hitx = 0
    if dx:
        b.x += dx
        y0 = int(b.y // TILE)
        y1 = int((b.y + b.h - 0.001) // TILE)
        if dx > 0:
            tx = int((b.x + b.w - 0.001) // TILE)
            for ty in range(y0, y1 + 1):
                if lvl.solid(tx, ty):
                    b.x = tx * TILE - b.w
                    hitx = 1
                    break
        else:
            tx = int(b.x // TILE)
            for ty in range(y0, y1 + 1):
                if lvl.solid(tx, ty):
                    b.x = (tx + 1) * TILE
                    hitx = -1
                    break
    down = up = False
    plat = None
    if dy:
        prev_bottom = b.y + b.h
        b.y += dy
        x0 = int(b.x // TILE)
        x1 = int((b.x + b.w - 0.001) // TILE)
        if dy > 0:
            ty = int((b.y + b.h - 0.001) // TILE)
            for tx in range(x0, x1 + 1):
                if lvl.solid(tx, ty) or (oneway and lvl.oneway(tx, ty) and prev_bottom <= ty * TILE + 0.5):
                    b.y = ty * TILE - b.h
                    down = True
                    break
            if plats and not down:
                for p in plats:
                    if b.x + b.w > p.x and b.x < p.x + p.w and prev_bottom <= p.y + abs(p.dy) + 0.5 and b.y + b.h >= p.y:
                        b.y = p.y - b.h
                        down = True
                        plat = p
                        break
        else:
            ty = int(b.y // TILE)
            for tx in range(x0, x1 + 1):
                if lvl.solid(tx, ty):
                    b.y = (ty + 1) * TILE
                    up = True
                    break
    return hitx, down, up, plat


