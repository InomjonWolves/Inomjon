    def run(self):
        acc = 0.0
        step = 1 / 60
        while True:
            dt = min(0.1, self.clock.tick(60) / 1000.0)
            self.events()
            acc += dt
            n = 0
            while acc >= step and n < 4:
                self.update()
                acc -= step
                n += 1
            if n == 4:
                acc = 0.0
            self.draw()
            pygame.display.flip()


