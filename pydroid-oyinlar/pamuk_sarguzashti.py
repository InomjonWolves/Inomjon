class Sound:
    def __init__(self):
        self.ok = False
        self.sfx_on = True
        self.music_on = True
        self.snd = {}
        self.music = None
        self.mch = None
        try:
            init = pygame.mixer.get_init()
            if not init:
                pygame.mixer.init(22050, -16, 1, 512)
                init = pygame.mixer.get_init()
            self.rate, size, self.ch = init
            if size != -16:
                return
            pygame.mixer.set_num_channels(12)
            self.ok = True
        except Exception:
            return
        try:
            self.build()
        except Exception:
            self.ok = False

    def make(self, samples):
        a = array.array("h", [int(clamp(v, -1.0, 1.0) * 30000) for v in samples])
        if self.ch == 2:
            b = array.array("h", bytes(len(a) * 4))
            b[0::2] = a
            b[1::2] = a
            a = b
        return pygame.mixer.Sound(buffer=a.tobytes())

    def synth(self, segs, vol=0.3, sustain=0.0):
        """segs: (f0, f1, sekund, toʻlqin) roʻyxati"""
        r = self.rate
        out = []
        ph = 0.0
        lp = 0.0
        for f0, f1, dur, wave in segs:
            n = max(1, int(r * dur))
            att = max(1, int(r * 0.004))
            for i in range(n):
                t = i / n
                f = f0 + (f1 - f0) * t
                ph += f / r
                fr = ph % 1.0
                if wave == "sq":
                    v = 0.8 if fr < 0.3 else -0.5
                elif wave == "tri":
                    v = 4 * abs(fr - 0.5) - 1
                elif wave == "sin":
                    v = math.sin(6.283185 * ph)
                else:  # shovqin, yumshatilgan
                    lp += (random.uniform(-1, 1) - lp) * (f0 / 4000.0)
                    v = lp * 2.2
                env = min(1.0, i / att) * (1.0 if t < sustain else (1 - (t - sustain) / (1 - sustain + 1e-9)) ** 1.4)
                out.append(v * env * vol)
        return self.make(out)

    def build(self):
        s = self.synth
        notes = lambda seq, w="sq", d=0.07, last=0.18: [(f, f, d if i < len(seq) - 1 else last, w) for i, f in enumerate(seq)]
