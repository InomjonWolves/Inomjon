    def bubble(self, txt, cx, by):
        f = self.fonts["s"]
        words = txt.split()
        maxw = int(self.view_rect.w * 0.6)
        lines, cur = [], ""
        for w in words:
            trial = (cur + " " + w).strip()
            if f.size(trial)[0] > maxw and cur:
                lines.append(cur)
                cur = w
            else:
                cur = trial
        lines.append(cur)
        imgs = [f.render(l, True, OUT) for l in lines]
        w = max(i.get_width() for i in imgs) + self.fs["s"]
        h = sum(i.get_height() for i in imgs) + self.fs["s"] // 2
        x = clamp(cx - w // 2, 6, self.view_rect.w - w - 6)
        y = max(6, by - h)
        pygame.draw.rect(self.view, OUT, (x - 2, y - 2, w + 4, h + 4), border_radius=self.fs["s"] // 2)
        pygame.draw.rect(self.view, (255, 252, 240), (x, y, w, h), border_radius=self.fs["s"] // 2)
        yy = y + self.fs["s"] // 4
        for im in imgs:
            self.view.blit(im, (x + (w - im.get_width()) // 2, yy))
            yy += im.get_height()

