        for tx in self.pits:
            if tx0 <= tx <= tx1:
                view.blit(self.pit_shade, (tx * T - ox, ys))
        for ty in range(ROWS):
            row = g[ty]
            for tx in range(tx0, tx1 + 1):
                c = row[tx]
                if c == ".":
                    continue
                X = tx * T - ox
                Y = ty * T + oy
                if c == "#":
                    top = ty == 0 or not lvl.solid(tx, ty - 1) or g[ty - 1][tx] in "Bcg"
                    left = tx > 0 and g[ty][tx - 1] != "#"
                    right = tx < lvl.w - 1 and g[ty][tx + 1] != "#"
                    bottom = ty < ROWS - 1 and g[ty + 1][tx] != "#"
