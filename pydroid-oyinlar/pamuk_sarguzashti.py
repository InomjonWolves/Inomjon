    def play(self, name):
        if self.ok and self.sfx_on and name in self.snd:
            try:
                self.snd[name].play()
            except Exception:
                pass

    def build_music(self):
        """Quvnoq qisqa kuy (4 takt, aylanib chalinadi). Fon oqimida yaratiladi."""
        if not self.ok:
            return
        r = self.rate
        step = 60.0 / 132 / 2  # sakkizlik nota
        mel = [72, None, 76, 79, 81, 79, 76, None, 77, None, 76, 74, 72, 74, 76, None,
               72, None, 76, 79, 84, 83, 81, None, 79, 77, 76, 74, 72, None, 67, None]
        bass = [48, 55, 52, 55, 53, 57, 48, 55, 45, 52, 48, 52, 43, 50, 48, 43]
        n = int(r * step * len(mel))
        buf = [0.0] * n
        mf = lambda m: 440.0 * 2 ** ((m - 69) / 12.0)
        ns = int(r * step)
        for i, m in enumerate(mel):
            if m is None:
                continue
            f = mf(m) / r
            base = i * ns
            ln = int(ns * 0.9)
            ph = 0.0
            for j in range(ln):
                ph += f
                v = 0.6 if (ph % 1.0) < 0.25 else -0.2
                buf[base + j] += v * 0.09 * (1 - j / ln) ** 0.8
        bs = ns * 2
        for i, m in enumerate(bass):
            f = mf(m) / r
            base = i * bs
            ph = 0.0
            for j in range(int(bs * 0.95)):
                ph += f
                buf[base + j] += (4 * abs((ph % 1.0) - 0.5) - 1) * 0.16 * (1 - j / bs) ** 0.5
        for i in range(0, len(mel)):  # yengil «chiq-chiq»
            if i % 2 == 1:
                base = i * ns
                for j in range(int(ns * 0.15)):
                    buf[base + j] += random.uniform(-1, 1) * 0.025 * (1 - j / (ns * 0.15))
        try:
            self.music = self.make(buf)
        except Exception:
            self.music = None
        self.update_music()

    def update_music(self):
        if not self.ok or self.music is None:
            return
        try:
            if self.music_on:
                if not (self.mch and self.mch.get_busy()):
                    self.mch = self.music.play(loops=-1)
                    if self.mch:
                        self.mch.set_volume(0.55)
            elif self.mch:
                self.mch.stop()
                self.mch = None
        except Exception:
            pass


