SAVE_NAME = "pamuk_saqlash.json"


def save_paths():
    out = []
    try:
        out.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), SAVE_NAME))
    except NameError:
        pass
    out.append(os.path.join(os.path.expanduser("~"), "." + SAVE_NAME))
    return out


def load_save():
    for p in save_paths():
        try:
            with open(p, encoding="utf-8") as f:
                d = json.load(f)
            if isinstance(d, dict):
                d["_path"] = p
                return d
        except Exception:
            pass
    return {}


def write_save(d):
    data = {k: v for k, v in d.items() if not k.startswith("_")}
    paths = ([d["_path"]] if d.get("_path") else []) + save_paths()
    for p in paths:
        try:
            with open(p, "w", encoding="utf-8") as f:
                json.dump(data, f)
            d["_path"] = p
            return True
        except Exception:
            continue
    return False


