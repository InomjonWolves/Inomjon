    def held_ctrls(self):
        held = set()
        for pos in self.pointers.values():
            for n, r in self.hit.items():
                if r.collidepoint(pos):
                    held.add(n)
        return held

    def tap(self, pos):
        if self.state == "play":
            if self.pause_rect.inflate(self.pause_rect.w * 0.6, self.pause_rect.h * 0.6).collidepoint(pos):
                self.pause()
            return
        for b in self.ui:
            if b.rect.collidepoint(pos):
                b.cb()
                return

    def pause(self):
        if self.state == "play":
            self.snd.play("click")
            self.state = "pause"
            self.build_ui()

    def back(self):
        if self.state == "play":
            self.pause()
        elif self.state == "pause":
            self.resume()
        elif self.state in ("select", "win", "over", "end"):
            self.goto("title" if self.state == "select" else "select")
        else:
            pygame.quit()
            sys.exit()

    def events(self):
        for e in pygame.event.get():
            t = e.type
            if t == pygame.QUIT:
                pygame.quit()
                sys.exit()
            elif t == pygame.FINGERDOWN:
                pos = (e.x * self.W, e.y * self.H)
                self.pointers[("f", e.finger_id)] = pos
                self.tap(pos)
            elif t == pygame.FINGERMOTION:
                self.pointers[("f", e.finger_id)] = (e.x * self.W, e.y * self.H)
            elif t == pygame.FINGERUP:
                self.pointers.pop(("f", e.finger_id), None)
            elif t == pygame.MOUSEBUTTONDOWN and not getattr(e, "touch", False) and e.button == 1:
                self.pointers["m"] = e.pos
                self.tap(e.pos)
            elif t == pygame.MOUSEMOTION and not getattr(e, "touch", False) and "m" in self.pointers:
                self.pointers["m"] = e.pos
            elif t == pygame.MOUSEBUTTONUP and not getattr(e, "touch", False):
                self.pointers.pop("m", None)
            elif t == pygame.KEYDOWN:
                if e.key in (pygame.K_ESCAPE, pygame.K_AC_BACK, pygame.K_p):
                    self.back()
                elif e.key in (pygame.K_SPACE, pygame.K_UP, pygame.K_w, pygame.K_z):
                    if self.state == "play":
                        self.inp.pressed = True
                    elif self.ui and e.key == pygame.K_SPACE:
                        self.ui[0].cb() if self.state != "select" else self.start_level(self.save["unlocked"] - 1)
                elif e.key == pygame.K_RETURN and self.ui:
                    self.ui[0].cb() if self.state != "select" else self.start_level(self.save["unlocked"] - 1)
            elif t in (getattr(pygame, "WINDOWFOCUSLOST", -1), getattr(pygame, "APP_WILLENTERBACKGROUND", -2)):
                self.pause()
                self.pointers.clear()
            elif t in (getattr(pygame, "WINDOWSIZECHANGED", -3), pygame.VIDEORESIZE):
                pass
        surf = pygame.display.get_surface()
        if surf is not None and surf.get_size() != self.size:
            self.screen = surf
            self.layout()

    def read_input(self):
        held = self.held_ctrls()
        keys = pygame.key.get_pressed()
        x = 0
        if "left" in held or keys[pygame.K_LEFT] or keys[pygame.K_a]:
            x -= 1
        if "right" in held or keys[pygame.K_RIGHT] or keys[pygame.K_d]:
            x += 1
        self.inp.x = x
        jh = "jump" in held or keys[pygame.K_SPACE] or keys[pygame.K_UP] or keys[pygame.K_w] or keys[pygame.K_z]
        if "jump" in held and "jump" not in self.prev_held:
            self.inp.pressed = True
        self.inp.held = jh
        self.prev_held = held

    # -------------------------------------------------- yangilash
    def update(self):
        self.t += 1
        if self.state != "play":
            self.update_parts()
            if self.state == "end" and self.t % 8 == 0:
                self.confetti(4, True)
            return
        self.read_input()
        lvl, p = self.lvl, self.player
        if self.banner_t:
            self.banner_t -= 1
        for pl in lvl.plats:
            pl.update()
        for key, cs in lvl.crumbles.items():
            if cs[0] == 1:
                cs[1] -= 1
                if cs[1] <= 0:
                    cs[0], cs[1] = 2, 0
                    self.burst(key[0] * TILE + 16, key[1] * TILE + 16, lvl.th["blk_c"], 6)
            elif cs[0] == 2:
                cs[1] += 1
                if cs[1] > 240:
                    # Pamuk yaqinida (ayniqsa ostida) boʻlsa, qayta tiklanmaydi
                    far = abs(p.x + p.w / 2 - (key[0] * TILE + 16)) > TILE * 3.5
                    above = p.y + p.h < key[1] * TILE - TILE * 2
                    if far or above:
                        cs[0] = 0
        if self.shake:
            self.shake -= 1
        self.update_parts()
        if self.finish:
            self.finish += 1
            if self.finish % 10 == 0:
                self.confetti(6)
            p.anim = 0
            p.t += 1
            if self.finish > 80:
                self.complete()
            return
        if p.dead:
            p.dead -= 1
            p.vy = min(MAX_FALL, p.vy + 0.6)
            p.y += p.vy
            if p.dead <= 0:
                self.after_death()
            return
        self.time += 1 / 60
        p.update(self.inp, self)
        self.inp.pressed = False
        if p.y > ROWS * TILE + 30:
            self.hearts -= 1
            self.kill_player()
            return
        # tikanlar
        x0, x1 = int(p.x // TILE), int((p.x + p.w - 0.01) // TILE)
        y0, y1 = int(p.y // TILE), int((p.y + p.h - 0.01) // TILE)
        for ty in range(y0, y1 + 1):
            for tx in range(x0, x1 + 1):
                if lvl.spike(tx, ty) and overlap(p, Box(tx * TILE + 4, ty * TILE + 15, 24, 17)):
                    p.hurt(self, tx * TILE + 16)
        # yoriq bloklar
        if p.on_ground:
            fy = int((p.y + p.h + 1) // TILE)
            for tx in range(x0, x1 + 1):
                cs = lvl.crumbles.get((tx, fy))
                if cs and cs[0] == 0:
                    cs[0], cs[1] = 1, 28
                    self.snd.play("crumble")
                    for side in (-1, 1):  # yonidagilar ham ketma-ket qulaydi
                        d = 1
                        while True:
                            nb = lvl.crumbles.get((tx + side * d, fy))
                            if not nb:
                                break
                            if nb[0] == 0:
                                nb[0], nb[1] = 1, 28 + 7 * d
                            d += 1
        # prujinalar
        for s in lvl.springs:
            if p.vy >= 0 and p.x + p.w > s.x + 3 and p.x < s.x + 29 and s.y + 12 <= p.y + p.h <= s.y + 34 and p.prev_bottom <= s.y + 26:
                p.vy = SPRING_V
                p.jumping = False
                p.on_ground = False
                p.y = s.y + 14 - p.h
                s.t = 12
                self.snd.play("spring")
            if s.t > 0:
                s.t -= 1
        # tangalar, yulduzlar, yuraklar
        for c in lvl.coins:
            if c.taken:
                continue
            if c.kind == "pop":
                c.vy = min(MAX_FALL, c.vy + 0.5)
                _, down, _, _ = move_body(c, lvl, c.vx, c.vy)
                if down:
                    c.vy = 0.0
                    c.vx *= 0.8
                c.t += 1
                if c.t < 115:  # biroz uchib, keyin olinadi
                    continue
            if overlap(p, c):
                c.taken = True
                self.got_coins += 1
                self.snd.play("coin")
                self.burst(c.x + 11, c.y + 11, GOLD, 5)
        for s in lvl.stars:
            if not s.taken and overlap(p, s):
                s.taken = True
                self.got_stars.add(s.i)
                self.snd.play("star")
                self.burst(s.x + 15, s.y + 15, (255, 230, 90), 18)
        for h in lvl.hearts:
            if not h.taken and overlap(p, h):
                h.taken = True
                self.hearts = min(MAX_HEARTS, self.hearts + 1)
                self.snd.play("heart")
                self.burst(h.x + 12, h.y + 12, (255, 110, 130), 12)
        for c in lvl.checks:
            if c.taken:
                continue
            if overlap(p, Box(c.x, c.y, 32, 64)):
                c.taken = True
                self.respawn = (c.x + 4, c.y + 64 - p.h)
                self.snd.play("check")
                self.burst(c.x + 22, c.y + 14, (255, 120, 120), 14)
        self.sign_show = None
        for s in lvl.signs:
            if abs((s.x + 16) - (p.x + p.w / 2)) < 80 and abs(s.y - p.y) < 90 and s.i < len(lvl.tips):
                self.sign_show = s
        g = lvl.goal
        if g and not g.taken and overlap(p, Box(g.x + 8, g.y, 32, 64)):
            self.finish = 1
            self.snd.play("win")
            self.burst(g.x + 24, g.y + 24, (255, 230, 120), 30)
            return
        # dushmanlar
        for e in lvl.enemies:
            e.update(self)
            if not e.alive or p.dead:
                continue
            if overlap(p, e):
                if e.stompable and p.vy > 0 and p.prev_bottom <= e.y + e.h * 0.55 + 2:
                    e.alive = False
                    e.dead_t = 0
                    p.vy = STOMP_HELD if self.inp.held else STOMP_V
                    p.jumping = False
                    self.snd.play("stomp")
                    self.burst(e.x + e.w / 2, e.y + e.h / 2, (240, 240, 250), 10)
                else:
                    p.hurt(self, e.x + e.w / 2)
        lvl.enemies = [e for e in lvl.enemies if e.alive or e.dead_t < 30]
        if lvl.boss:
            lvl.boss.update(self)
        tgt = self.cam_target()
        self.cam += (tgt - self.cam) * 0.12

    def update_parts(self):
        out = []
        for q in self.parts:
            q[0] += q[2]
            q[1] += q[3]
            q[3] += q[8]
            q[4] -= 1
            if q[4] > 0:
                out.append(q)
        self.parts = out[-260:]

