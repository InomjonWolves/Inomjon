class Art:
    """Ekran oʻlchamiga moslab bir marta chiziladigan rasmlar."""

    def __init__(self, k):
        self.k = k
        self.cat = {}
        for pose, frames in (("idle", 2), ("run", 4), ("jump", 1), ("fall", 1), ("wall", 1)):
            for f in range(frames):
                s = draw_cat(k, pose, f)
                self.cat[(pose, f, 1)] = s
                self.cat[(pose, f, -1)] = pygame.transform.flip(s, True, False)
        for name, kw in (("blink", dict(pose="idle", blink=True)), ("hurt", dict(pose="fall", hurt=True))):
            s = draw_cat(k, **kw)
            self.cat[(name, 0, 1)] = s
            self.cat[(name, 0, -1)] = pygame.transform.flip(s, True, False)
        self.en = {}
        for kind, fn in (("w", draw_mouse), ("h", draw_hedgehog), ("b", draw_bee), ("d", draw_dust)):
            for f in range(2):
                s = fn(k, f)
                self.en[(kind, f, 1)] = s
                self.en[(kind, f, -1)] = pygame.transform.flip(s, True, False)
        for f in range(2):
            self.en[("a", f, 1)] = self.en[("b", f, 1)]
            self.en[("a", f, -1)] = self.en[("b", f, -1)]
        self.boss = {}
        for mode in ("calm", "angry", "dizzy"):
            for f in range(2):
                s = draw_boss(k, mode, f)
                self.boss[(mode, f, 1)] = s
                self.boss[(mode, f, -1)] = pygame.transform.flip(s, True, False)
        self.coin = [draw_coin(k, f) for f in range(8)]
        self.star = draw_star(k)
        self.star_ghost = draw_star(k, True)
        self.heart = draw_heart(k)
        self.spring = [draw_spring(k, False), draw_spring(k, True)]
        self.check = {(on, f): draw_check(k, on, f) for on in (0, 1) for f in (0, 1)}
        self.goal = [draw_goal(k, f) for f in range(2)]
        self.sign = draw_sign(k)


